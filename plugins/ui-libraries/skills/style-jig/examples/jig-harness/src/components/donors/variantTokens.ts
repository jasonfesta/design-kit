export function getStyleVariantSpec(styleId: DonorStyleId, variantIdx: number): StyleVariantSpec | null {
  const list = STYLE_VARIANTS[styleId];
  if (!list || list.length === 0) return null;
  const clamped = Math.max(0, Math.min(list.length - 1, Math.floor(variantIdx || 0)));
  return list[clamped] ?? null;
}

export function resolveVariantPolarityTokens(
  styleId: DonorStyleId,
  variantIdx: number,
  polarity: DonorPolarity
): VariantPolarityTokens | null {
  const spec = getStyleVariantSpec(styleId, variantIdx);
  if (!spec) return null;
  return polarity === 'dark' ? spec.dark : spec.light;
}
